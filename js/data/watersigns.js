/**
 * Schifffahrtszeichen an Land – die Tafeln am Ufer, an Brücken und Schleusen.
 *
 * Nach den deutschen Verkehrsvorschriften (Anlage zur Binnenschifffahrts-
 * straßen-Ordnung, sinngleich auf den Seeschifffahrtsstraßen). Andere Länder
 * haben eigene Tafeln; die europäischen Binnenreviere folgen weitgehend
 * demselben Muster, aber verlassen sollte man sich darauf nicht.
 *
 * Die vier Klassen erkennt man an der Tafel, noch bevor man das Sinnbild
 * darauf lesen kann – und genau darum geht es aus der Entfernung:
 *
 *   verbot          weiß mit rotem Rand und rotem Schrägbalken – hier nicht
 *   gebot           weiß mit rotem Rand, ohne Schrägbalken – hier musst du
 *   einschraenkung  weiß mit rotem Rand, schwarze Angabe – so viel geht
 *   hinweis         blau mit weißem Sinnbild – hier kannst du
 *
 * Das allgemeine Fahrverbot fällt aus der Reihe: eine rote Tafel mit einem
 * weißen Querstreifen. Sie ist das einzige Zeichen, das man auch dann nicht
 * verwechseln kann, wenn man gar nichts über die Systematik weiß.
 *
 * ZUR EHRLICHKEIT: Gezeichnet wird die Klasse der Tafel, nicht das Sinnbild
 * darauf – das steht daneben im Text. Ein nachgemaltes Sinnbild, das nicht
 * genau stimmt, wäre schlimmer als eine ehrliche Beschreibung.
 */

