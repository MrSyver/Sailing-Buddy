/** Trifft ein Knoten alle gewählten Merkmale? */
export function matchesKnot(knot, uses, traits) {
  const passtZweck = uses.size === 0 || [...uses].some((u) => knot.use.includes(u));
  const passtArt = traits.size === 0 || [...traits].every((tr) => knot.traits.includes(tr));
  return passtZweck && passtArt;
}
