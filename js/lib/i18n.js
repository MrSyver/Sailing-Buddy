const DICT = { de: DE, en: EN };

/** Aktuelle Sprache der Oberfläche. */
export function uiLang() {
  const l = settings.get('uiLang');
  return DICT[l] ? l : 'de';
}

/**
 * Übersetzt einen Schlüssel. Platzhalter der Form {name} werden aus `vars` ersetzt.
 */
export function t(key, vars = null) {
  const lang = uiLang();
  let text = DICT[lang]?.[key] ?? DE[key] ?? key;
  if (vars) {
    text = text.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? String(vars[k]) : m));
  }
  return text;
}

/**
 * Holt ein sprachabhängiges Feld aus einem Datensatz.
 * Deutsche Fassung steht direkt im Objekt, englische unter `en`.
 */
export function loc(obj, field) {
  if (!obj) return undefined;
  if (uiLang() === 'en' && obj.en && obj.en[field] !== undefined) return obj.en[field];
  return obj[field];
}

/** Sprachcode für Datums- und Zeitformate. */
export function locale() {
  return uiLang() === 'en' ? 'en-GB' : 'de-DE';
}

/**
 * Zahl mit dem Dezimalzeichen der eingestellten Sprache.
 * Auf Deutsch also 32,4 statt 32.4 – an Bord wird nach Karte gearbeitet,
 * und dort steht das Komma.
 */
export function num(value, digits = 1) {
  if (value === null || value === undefined || !isFinite(value)) return '–';
  return value.toLocaleString(locale(), {
    minimumFractionDigits: digits,
    maximumFractionDigits: digits,
  });
}
